test('database menu duckdb: background completion updates actions without dismissing the menu', async () => {
  await page.getByRole('button', { name: 'Connect database', exact: true }).click()
  const form = page.getByRole('dialog')
  await form.getByLabel('Database engine').selectOption('duckdb')
  await form.getByLabel('Open mode').selectOption('memory')
  await form.getByRole('button', { name: 'Connect', exact: true }).click()
  await expect(form).not.toBeVisible()
  await expect(page.getByRole('button', { name: /^Run SQL/ })).toBeEnabled()
  await page.evaluate(() => {
    const off = window.dbCommander.onEvent(event => {
      if ('sessionId' in event) { (window as any).__menuSession = event.sessionId; off() }
    })
  })
  await page.locator('.monaco-editor').click()
  await page.keyboard.press(process.platform === 'darwin' ? 'Meta+A' : 'Control+A')
  await page.keyboard.insertText('SELECT 1; SELECT sum(sin(i)) FROM range(1000000000) AS t(i);')
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: /^Run SQL/ }).click()
  await expect(page.locator('.status-text')).toHaveText('Running')
  await expect.poll(() => page.evaluate(() => (window as any).__menuSession)).toBeTruthy()
  await page.locator('.database-node.current > button').first().click({ button: 'right' })
  const menu = page.getByRole('menu', { name: 'Explorer actions' })
  await expect(menu.getByRole('menuitem', { name: 'Visual query builder', exact: true })).toBeDisabled()
  // Finish the query without clicking outside the menu.
  await page.evaluate(() => window.dbCommander.cancel((window as any).__menuSession))
  await expect(page.locator('.status-text')).toHaveText('Cancelled')
  await expect(menu).toBeVisible()
  await expect(menu.getByRole('menuitem', { name: 'Visual query builder', exact: true })).toBeEnabled()
  await menu.getByRole('menuitem', { name: 'Database backup and restore', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Database backup and restore', exact: true })).toBeVisible()
})


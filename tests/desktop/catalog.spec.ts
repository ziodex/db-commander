import { tableAction, tableNode } from './explorer-actions'
import { _electron as electron, test, expect } from '@playwright/test'
import { mkdtempSync, readFileSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'
import { quoteIdentifier } from '../../src/shared/sql/common'
import { engineSchema } from '../../src/shared/contracts'

for (const engine of engineSchema.options) test(`catalog ${engine}: object groups, definitions, refresh and preserved transactions`, async ({}, testInfo) => {
  test.setTimeout(120000)
  test.skip(!(process.env.SQLCOMMANDER_TEST_DRIVERS ?? '').split(',').includes(engine === 'azure-sql' ? 'sqlserver' : engine), 'Engine not selected by Docker runner')
  const directory = mkdtempSync(join(tmpdir(), 'dbcommander-browse-ui-')), env: Record<string, string | undefined> = { ...process.env, SQLCOMMANDER_USER_DATA: directory }
  delete env.ELECTRON_RUN_AS_NODE
  const app = await electron.launch({ ...(process.env.SQLCOMMANDER_TEST_EXECUTABLE ? { executablePath: process.env.SQLCOMMANDER_TEST_EXECUTABLE } : { args: [resolve('.')] }), env: env as Record<string, string> })
  const page = await app.firstWindow(), name = `catalog_ui_${Date.now()}`, q = (value: string) => quoteIdentifier(value, engine)
  async function run(sql: string) {
    await expect(page.getByRole('button', { name: /^Run SQL/ })).toBeEnabled()
    await page.locator('.monaco-editor').click(); await page.keyboard.press(process.platform === 'darwin' ? 'Meta+A' : 'Control+A'); await page.keyboard.insertText(sql); await page.keyboard.press('Escape')
    await page.getByRole('button', { name: /^Run SQL/ }).click(); await expect(page.locator('.status-text')).toHaveText('Completed')
    await expect(page.getByRole('button', { name: /^Run SQL/ })).toBeEnabled()
    await expect(page.getByRole('button', { name: 'Refresh schema', exact: true })).toBeEnabled({ timeout: 60000 })
  }
  try {
    await expect(page.getByText('Saved locally', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Connect database', exact: true }).click()
    const form = page.getByRole('dialog'); await form.getByLabel('Database engine').selectOption(engine)
    if (['sqlite', 'duckdb'].includes(engine)) {
      await form.getByLabel('Open mode').selectOption('create'); await form.getByLabel('Database file').fill(join(directory, 'data.db'))
    } else {
      const prefix = engine === 'postgres' ? 'PG' : engine === 'azure-sql' ? 'SQLSERVER' : engine.toUpperCase()
      await form.getByLabel('Port', { exact: true }).fill(process.env[`SQLCOMMANDER_${prefix}_PORT`]!)
      await form.getByLabel(engine === 'oracle' ? 'Service name' : 'Database', { exact: true }).fill(engine === 'oracle' ? 'FREEPDB1' : 'dbcommander')
      await form.getByLabel('User', { exact: true }).fill('dbcommander'); await form.getByLabel('Password', { exact: true }).fill(['sqlserver', 'azure-sql'].includes(engine) ? 'Local-Test-Only!2026' : 'local-test-only')
      if (engine !== 'oracle') { await form.getByText('Custom CA certificate', { exact: true }).click(); await form.getByLabel('CA certificate PEM').fill(readFileSync(process.env[`SQLCOMMANDER_${prefix}_CA`]!, 'utf8')) }
    }
    await form.getByRole('button', { name: 'Connect', exact: true }).click(); await expect(form).not.toBeVisible()
    await run(`CREATE TABLE ${q(name)} (${q('id')} INTEGER PRIMARY KEY,${q('Display Name')} VARCHAR(100) DEFAULT 'catalog default',${q('parent_id')} INTEGER,CONSTRAINT ${q(name+'_fk')} FOREIGN KEY (${q('parent_id')}) REFERENCES ${q(name)} (${q('id')}),CONSTRAINT ${q(name+'_check')} CHECK (${q('id')} >= 0))`)
    await run(`CREATE INDEX ${q(name+'_idx')} ON ${q(name)} (${q('Display Name')})`)
    await run(`CREATE VIEW ${q(name+'_view')} AS SELECT ${q('id')} FROM ${q(name)}`)
    await page.getByLabel('Filter database objects').fill(name)
    const detail = page.getByRole('dialog', { name: 'Object details', exact: true })
    if (engine === 'oracle') {
      // Exercise materialized-view inspection without prewarming native metadata.
      await run(`CREATE MATERIALIZED VIEW ${q(name+'_mv')} AS SELECT ${q('id')} FROM ${q(name)}`)
      await page.getByLabel('Object kind', { exact: true }).selectOption('materialized view')
      await expect(tableNode(page, name+'_mv')).toHaveCount(1)
      await tableAction(page, name+'_mv', 'Object details')
      await expect(detail.getByLabel('Object definition')).toHaveValue(/CREATE MATERIALIZED VIEW/)
      await expect(detail.getByText('Generated summary', { exact: true })).toBeVisible()
      await expect(detail.getByText(/Logical summary from Oracle catalog metadata, not full native DDL/)).toBeVisible()
      await expect(detail.getByRole('table', { name: 'Columns', exact: true })).toContainText('id')
      await detail.getByRole('button', { name: 'Refresh object', exact: true }).click()
      await expect(detail.getByRole('button', { name: 'Copy definition', exact: true })).toBeEnabled({ timeout: 60000 })
      await expect(detail.getByLabel('Object definition')).toHaveValue(/CREATE MATERIALIZED VIEW/)
      await page.screenshot({ path: testInfo.outputPath('oracle-materialized-view.png') })
      await detail.getByRole('button', { name: 'Close object details', exact: true }).click()
    }
    await page.getByLabel('Object kind', { exact: true }).selectOption('all')
    await page.getByLabel('Filter database objects').fill('')
    const relation = page.locator('.relation-node').filter({ has: tableNode(page, name) })
    const indexButton = relation.getByRole('button', { name: new RegExp(`^Object details ${name}_idx`) })
    await expect(indexButton).not.toBeVisible()
    const editorBeforeExpand = await page.locator('.monaco-editor').innerText()
    await page.getByRole('button', { name: `Expand table ${name}`, exact: true }).focus()
    await page.keyboard.press('Enter')
    await expect(relation.getByText('Indexes', { exact: true })).toBeVisible()
    await expect(indexButton).not.toBeVisible()
    await relation.getByText('Indexes', { exact: true }).click()
    await expect(indexButton).toBeVisible()
    await expect(relation.getByText('foreign key', { exact: true })).not.toBeVisible()
    await relation.getByText('Keys', { exact: true }).click()
    await expect(relation.getByText('foreign key', { exact: true })).toBeVisible()
    await expect(relation.getByText('Constraints', { exact: true })).toHaveCount(engine === 'sqlite' ? 0 : 1)
    expect(await page.locator('.monaco-editor').innerText()).toBe(editorBeforeExpand)
    await page.screenshot({ path: testInfo.outputPath(`${engine}-table-collections.png`) })
    await page.getByRole('button', { name: `Collapse table ${name}`, exact: true }).click()
    await expect(indexButton).not.toBeVisible()
    // A matching child must reveal its owning table even when the table kind is filtered out.
    await page.getByLabel('Filter database objects').fill(name+'_idx')
    await page.getByLabel('Object kind', { exact: true }).selectOption('index')
    await expect(tableNode(page, name)).toHaveCount(1)
    await expect(indexButton).toBeVisible()
    await indexButton.click()
    await expect(detail.getByLabel('Object definition')).not.toHaveValue('')
    await expect(detail.getByRole('button', { name: 'Close object details', exact: true })).toBeEnabled()
    await page.keyboard.press('Escape'); await expect(detail).not.toBeVisible()
    await page.getByLabel('Filter database objects').fill('foreign key')
    await page.getByLabel('Object kind', { exact: true }).selectOption('constraint')
    await expect(relation.getByText('foreign key', { exact: true })).toBeVisible()
    await relation.getByRole('button').filter({ has: page.getByText('foreign key', { exact: true }) }).click()
    await expect(detail.getByLabel('Object definition')).toHaveValue(/REFERENCES/i)
    await detail.getByRole('button', { name: 'Close object details', exact: true }).click()
    await page.getByLabel('Filter database objects').fill(name)
    await page.getByLabel('Object kind', { exact: true }).selectOption('table')
    await tableAction(page, `${name}`, 'Object details')
    await expect(detail.getByLabel('Object definition')).toContainText('CREATE TABLE')
    await expect(detail.getByRole('table', { name: 'Columns', exact: true })).toContainText('Display Name')
    await expect(detail.getByRole('table', { name: 'Indexes', exact: true })).toContainText(name+'_idx')
    const sql = await detail.getByLabel('Object definition').inputValue()
    await detail.getByRole('button', { name: 'Copy definition', exact: true }).click()
    await expect(detail.getByRole('status')).toHaveText('Definition copied.')
    expect(await app.evaluate(({ clipboard }) => clipboard.readText())).toBe(sql)
    const file = join(directory, 'definition.sql')
    await app.evaluate(({ dialog }, file) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: file }) }, file)
    await detail.getByRole('button', { name: 'Save definition', exact: true }).click()
    await expect(detail.getByRole('status')).toHaveText('Definition saved.')
    expect(readFileSync(file, 'utf8')).toBe(sql)
    await page.screenshot({ path: testInfo.outputPath(`${engine}-object-details.png`) })
    await detail.getByRole('button', { name: 'Close object details', exact: true }).click()
    await page.getByRole('button', { name: 'Begin', exact: true }).click()
    await expect(page.locator('.transaction-badge')).toHaveText('In transaction')
    await expect(page.getByRole('button', { name: /^Run SQL/ })).toBeEnabled()
    await expect(page.getByRole('button', { name: 'Refresh schema', exact: true })).toBeEnabled({ timeout: 60000 })
    const buffer = await page.locator('.monaco-editor').innerText(), history = await page.evaluate(() => window.dbCommander.history())
    await tableAction(page, `${name}`, 'Object details')
    await expect(detail.getByRole('button', { name: 'Open definition in new tab', exact: true })).toBeEnabled()
    await detail.getByRole('button', { name: 'Refresh object', exact: true }).click()
    await expect(detail.getByRole('button', { name: 'Open definition in new tab', exact: true })).toBeEnabled()
    await detail.getByRole('button', { name: 'Open definition in new tab', exact: true }).click()
    await expect(page.getByRole('tab', { name: name+'.sql', exact: true })).toHaveAttribute('aria-selected','true')
    await expect(page.getByRole('button', { name: /^Run SQL/ })).toBeEnabled()
    await expect(page.locator('.monaco-editor')).toContainText('CREATE TABLE')
    expect((await page.evaluate(() => window.dbCommander.history())).length).toBe(history.length)
    await page.getByRole('tab', { name: 'Untitled.sql', exact: true }).click()
    await expect.poll(() => page.locator('.monaco-editor').innerText()).toBe(buffer)
    await expect(page.locator('.transaction-badge')).toHaveText('In transaction')
    await page.getByRole('button', { name: 'Rollback', exact: true }).click(); await expect(page.locator('.status-text')).toHaveText('Completed')
    await run(`ALTER TABLE ${q(name)} ADD ${q('fresh_column')} INTEGER`)
    await tableAction(page, `${name}`, 'Object details')
    await expect(detail.getByRole('table', { name: 'Columns', exact: true })).toContainText('fresh_column')
    await detail.getByRole('button', { name: 'Close object details', exact: true }).click()
    await page.getByLabel('Object kind', { exact: true }).selectOption('view')
    await tableAction(page, `${name}_view`, 'Object details')
    await expect(detail.getByLabel('Object definition')).toHaveValue(/select/i)
    await detail.getByRole('button', { name: 'Close object details', exact: true }).click()
    if (engine === 'oracle') await run(`DROP MATERIALIZED VIEW ${q(name+'_mv')}`)
    await run(`DROP VIEW ${q(name+'_view')}`); await run(`DROP TABLE ${q(name)}`)
    await expect(tableNode(page, `${name}_view`)).toHaveCount(0)
  } finally {
    await app.evaluate(({ app }) => app.exit()).catch(() => {}); await app.close().catch(() => {}); rmSync(directory, { recursive: true, force: true })
  }
})

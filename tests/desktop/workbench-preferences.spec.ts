import { waitForWorkspaceReady } from './workspace-ready'
import { _electron as electron, test, expect, type ElectronApplication } from '@playwright/test'
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'

test('readable workbench, connection context actions and application-wide preferences', async ({}, info) => {
  test.setTimeout(120_000)
  const directory = mkdtempSync(join(tmpdir(), 'dbcommander-preferences-ui-'))
  const env: Record<string, string | undefined> = { ...process.env, SQLCOMMANDER_USER_DATA: directory }; delete env.ELECTRON_RUN_AS_NODE
  let app: ElectronApplication | undefined
  async function launch() {
    app = await electron.launch({ args: [resolve('.')], env: env as Record<string, string> })
    const page = await app.firstWindow()
    await waitForWorkspaceReady(page)
    return page
  }
  async function close() { await app?.evaluate(({ app }) => app.exit(0)); await app?.close(); app = undefined }
  try {
    let page = await launch()
    await page.evaluate(async () => {
      const old = (await window.dbCommander.loadWorkspace())!
      const config = { engine: 'duckdb' as const, name: 'Local analytics', host: 'local', port: 1, user: 'local', database: 'DuckDB', tls: 'disable' as const, duckdbMode: 'memory' as const }
      await window.dbCommander.saveWorkspace({ version: 2, tabs: old.tabs, activeTabId: old.activeTabId, profiles: [{ id: crypto.randomUUID(), config }] })
    })
    await page.reload(); await waitForWorkspaceReady(page)
    await expect(page.locator('.titlebar')).not.toContainText(/Db Commander|Primary|PREVIEW/)
    await expect(page.locator('.editor-tabs').getByRole('button', { name: 'File', exact: true })).toHaveCount(0)
    await expect(page.locator('.editor-tabs').getByRole('button', { name: 'Save SQL file', exact: true })).toHaveCount(0)
    await expect(page.locator('.monaco-editor .view-lines')).toHaveCSS('font-size', '13px')
    await expect(page.locator('.sidebar-title')).toHaveCSS('font-size', '14px')
    await expect(page.locator('.statusbar')).toHaveCSS('font-size', '12px')
    await expect(page.locator('.editor-tabs .dialect-label')).toHaveCount(0)
    await expect(page.locator('.statusbar .dialect-label')).toHaveText('SQL')
    await expect(page.locator('.statusbar .dialect-label')).toHaveAttribute('title', 'Not connected')
    await expect(page.locator('.titlebar')).toHaveCSS('font-size', '12px')
    await expect(page.getByRole('button', { name: /^Actions for / })).toHaveCount(0)

    const connection = page.getByRole('button', { name: 'Open Local analytics in new tab', exact: true })
    const connectedIndicator = connection.locator('.online-dot')
    await expect(page.getByText('Current connection', { exact: true })).toHaveCount(0)
    await expect(connectedIndicator).toHaveCount(0)
    await expect(connection).toHaveAttribute('aria-description', 'DuckDB · Not connected')
    await connection.click({ button: 'right' })
    await expect(page.getByRole('menu', { name: 'Connection actions for Local analytics' })).toBeVisible()
    await page.getByRole('menuitem', { name: 'Edit connection', exact: true }).click()
    const edit = page.getByRole('dialog')
    await expect(edit.getByLabel('Connection name', { exact: true })).toHaveValue('Local analytics')
    await edit.getByRole('button', { name: 'Cancel', exact: true }).click()
    await connection.focus(); await page.keyboard.press('Shift+F10')
    await page.getByRole('menuitem', { name: 'Delete connection', exact: true }).click()
    const confirmation = page.getByRole('dialog')
    await expect(confirmation).toContainText('Delete')
    await confirmation.getByRole('button', { name: /Keep/ }).click()
    await expect(connection).toBeVisible()
    await connection.click(); await expect(page.locator('.status-text')).toHaveText('Connected')
    await expect(connectedIndicator).toBeVisible()
    await expect(connection).toHaveAttribute('aria-description', 'DuckDB · Connected · Used by the active tab')
    await expect(connection).toHaveAttribute('aria-current', 'true')
    await expect(page.locator('.status-text')).toHaveClass(/sr-only/)
    await expect(page.locator('.statusbar .dialect-label')).toHaveText('DuckDB')
    await expect(page.locator('.statusbar .dialect-label')).toHaveAttribute('title', 'Local analytics / memory')
    await expect(page.locator('.statusbar')).not.toContainText('Local analytics')
    await expect(page.locator('.statusbar .online-dot')).toHaveCount(0)
    const filter = page.getByLabel('Object kind', { exact: true })
    await expect(filter).toBeVisible()
    for (const [width, height, zoom] of [[1440, 940, 1], [1024, 700, 1], [1440, 940, 2], [1024, 700, 2]]) {
      await app!.evaluate(({ BrowserWindow }, { width, height, zoom }) => { const window = BrowserWindow.getAllWindows()[0]; window.setSize(width, height); window.webContents.setZoomFactor(zoom) }, { width, height, zoom })
      const fit = await filter.evaluate(element => { const style = getComputedStyle(element); return element.clientHeight - parseFloat(style.paddingTop) - parseFloat(style.paddingBottom) >= parseFloat(style.fontSize) * 1.2 })
      expect(fit).toBe(true)
      for (const name of ['Workspace', 'Toggle sidebar', 'Toggle results', 'Commands']) await expect(page.getByRole('button', { name, exact: true })).toBeInViewport({ ratio: 1 })
      await expect(page.locator('.statusbar .dialect-label')).toBeInViewport({ ratio: 1 })
      await expect(page.locator('.statusbar').getByText('Saved locally', { exact: true })).toBeInViewport({ ratio: 1 })
      await expect(connectedIndicator).toBeInViewport({ ratio: 1 })
      await expect(page.locator('.monaco-editor .view-lines').first()).toHaveCSS('font-size', '13px')
      const screenshot = await app!.evaluate(async ({ BrowserWindow }) => (await BrowserWindow.getAllWindows()[0].webContents.capturePage()).toPNG().toString('base64'))
      writeFileSync(info.outputPath(`workbench-${width}-${zoom}.png`), screenshot, 'base64')
      await page.getByRole('button', { name: 'Application preferences', exact: true }).click()
      const form = page.getByRole('dialog', { name: 'Preferences', exact: true })
      if (zoom === 1) await expect(form).toHaveCSS('width', '840px')
      for (const name of ['Display', 'Shortcuts', 'Tabs', 'Indentation', 'SQL formatting', 'Import / export']) {
        const tab = form.getByRole('tab', { name, exact: true })
        await tab.click(); await expect(tab).toHaveAttribute('aria-selected', 'true')
        await expect(tab).toBeInViewport({ ratio: 1 })
        await expect(form.getByRole('tabpanel')).toHaveCount(1)
        if (name === 'Tabs') {
          const switchWarning = form.getByRole('checkbox', { name: 'Confirm before switching databases', exact: true })
          await switchWarning.scrollIntoViewIfNeeded(); await expect(switchWarning).toBeInViewport({ ratio: 1 })
        }
        for (const action of ['Reset defaults', 'Cancel', 'Apply settings']) await expect(form.getByRole('button', { name: action, exact: true })).toBeInViewport({ ratio: 1 })
        const screenshot = await app!.evaluate(async ({ BrowserWindow }) => (await BrowserWindow.getAllWindows()[0].webContents.capturePage()).toPNG().toString('base64'))
        writeFileSync(info.outputPath(`preferences-${name.replace(/\W+/g, '-')}-${width}-${zoom}.png`), screenshot, 'base64')
      }
      await page.keyboard.press('Home'); await expect(form.getByRole('tab', { name: 'Display', exact: true })).toBeFocused()
      await page.keyboard.press('ArrowRight'); await expect(form.getByRole('tab', { name: 'Shortcuts', exact: true })).toHaveAttribute('aria-selected', 'true')
      await page.keyboard.press('End'); await expect(form.getByRole('tab', { name: 'Import / export', exact: true })).toBeFocused()
      await page.keyboard.press('Escape')
    }
    await app!.evaluate(({ BrowserWindow }) => { const window = BrowserWindow.getAllWindows()[0]; window.setSize(1440, 940); window.webContents.setZoomFactor(1) })
    await page.getByRole('button', { name: /^Run SQL/ }).click()
    await expect(page.locator('.status-text')).toHaveText('Completed')
    await expect(page.locator('.status-text')).not.toHaveClass(/sr-only/)
    await expect(page.locator('.status-text')).toBeVisible()
    await page.getByRole('tab', { name: 'Untitled.sql', exact: true }).click()
    await expect(page.locator('.statusbar .dialect-label')).toHaveText('SQL')
    await expect(connectedIndicator).toBeVisible()
    await page.getByRole('tab', { name: 'Query 2.sql', exact: true }).click()
    await expect(page.locator('.statusbar .dialect-label')).toHaveText('DuckDB')
    await page.getByRole('button', { name: 'New query tab', exact: true }).click()
    await expect(page.locator('.status-text')).toHaveText('Connected')
    await expect(connectedIndicator).toHaveCount(1)
    await page.getByRole('button', { name: 'Disconnect', exact: true }).click()
    await expect(page.locator('.status-text')).toHaveText('Disconnected')
    await expect(connectedIndicator).toBeVisible()
    await page.getByRole('button', { name: 'Close Query 2.sql', exact: true }).click()
    await page.getByRole('dialog', { name: 'Close query tab', exact: true }).getByRole('button', { name: 'Close tab', exact: true }).click()
    await expect(connectedIndicator).toHaveCount(0)
    await expect(connection).toHaveAttribute('aria-description', 'DuckDB · Not connected · Used by the active tab')
    await page.getByRole('button', { name: 'Connect database', exact: true }).click()
    await page.getByRole('dialog').getByRole('button', { name: 'Connect', exact: true }).click()
    await expect(connectedIndicator).toBeVisible()
    await page.getByRole('button', { name: 'Application preferences', exact: true }).click()
    const draft = page.getByRole('dialog', { name: 'Preferences', exact: true })
    await draft.getByLabel(/Font size/).fill('99')
    await draft.getByRole('tab', { name: 'Indentation', exact: true }).click()
    await draft.getByLabel(/Indent width/).fill('4')
    await draft.getByRole('button', { name: 'Apply settings', exact: true }).click()
    await expect(draft.getByRole('tab', { name: 'Display', exact: true })).toHaveAttribute('aria-selected', 'true')
    await expect(draft.getByLabel(/Font size/)).toBeFocused()
    await draft.getByLabel(/Font size/).fill('13')
    await draft.getByRole('tab', { name: 'Indentation', exact: true }).click()
    await expect(draft.getByLabel(/Indent width/)).toHaveValue('4')
    await draft.getByRole('button', { name: 'Cancel', exact: true }).click()
    const created = app!.waitForEvent('window')
    await page.evaluate(() => window.dbCommander.createWorkspaceWindow('Preferences check'))
    const second = await created; await waitForWorkspaceReady(second)
    await second.locator('.activity-bar').getByRole('button', { name: 'Application preferences', exact: true }).click()
    const preferences = second.getByRole('dialog', { name: 'Preferences', exact: true })
    await expect(preferences).toContainText('all application windows')
    await preferences.getByLabel('Appearance', { exact: true }).selectOption('light')
    await preferences.getByRole('tab', { name: 'Tabs', exact: true }).click()
    await preferences.getByRole('checkbox', { name: 'Confirm before closing a tab', exact: true }).uncheck()
    await preferences.getByRole('checkbox', { name: 'Confirm before switching databases', exact: true }).uncheck()
    await preferences.getByRole('button', { name: 'Apply settings', exact: true }).click()
    await expect(preferences).toBeHidden()
    await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
    await expect(second.locator('html')).toHaveAttribute('data-theme', 'light')
    await expect(connectedIndicator).toBeVisible()
    const primaryWindow = await app!.browserWindow(page)
    const lightWorkbench = await primaryWindow.evaluate(async window => (await window.webContents.capturePage()).toPNG().toString('base64'))
    writeFileSync(info.outputPath('workbench-connected-light.png'), lightWorkbench, 'base64')
    await expect(page.locator('.monaco-editor .view-lines').first()).toHaveCSS('font-size', '13px')
    await page.locator('.activity-bar').getByRole('button', { name: 'Application preferences', exact: true }).click()
    await expect(page.getByRole('dialog', { name: 'Preferences' }).getByLabel('Appearance')).toHaveValue('light')
    await page.getByRole('dialog', { name: 'Preferences' }).getByRole('tab', { name: 'Tabs', exact: true }).click()
    await expect(page.getByRole('checkbox', { name: 'Confirm before closing a tab', exact: true })).not.toBeChecked()
    await expect(page.getByRole('checkbox', { name: 'Confirm before switching databases', exact: true })).not.toBeChecked()
    await page.keyboard.press('Escape')
    await close(); page = await launch()
    await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
    await expect(page.locator('.profile-list .online-dot')).toHaveCount(0)
    expect((await page.evaluate(() => window.dbCommander.preferences()))?.fontSize).toBe(13)
    await page.getByRole('button', { name: 'Application preferences', exact: true }).click()
    await page.getByRole('dialog', { name: 'Preferences' }).getByRole('tab', { name: 'Tabs', exact: true }).click()
    await expect(page.getByRole('checkbox', { name: 'Confirm before closing a tab', exact: true })).not.toBeChecked()
    await expect(page.getByRole('checkbox', { name: 'Confirm before switching databases', exact: true })).not.toBeChecked()
  } finally { await close(); rmSync(directory, { recursive: true, force: true, maxRetries: 10, retryDelay: 100 }) }
})
